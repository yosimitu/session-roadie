/** コマンドの説明（機能の1文）に、補足を箇条書きで続ける。commander はこの後ろに Options を出す */
export function describe(summary: string, key: string): string {
  const notes = NOTES[key];
  if (!notes) throw new Error(`補足がありません: ${key}`);
  // 先頭が空白の行は、直前の項目の続き
  const body = notes.map((l) => (l.startsWith(' ') ? `    ${l.trimStart()}` : `  - ${l}`)).join('\n');
  return `${summary}\n\n補足:\n${body}`;
}
